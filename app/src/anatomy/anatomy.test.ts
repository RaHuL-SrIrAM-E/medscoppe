import { describe, expect, it } from 'vitest';
import registryDoc from '../../public/anatomy/structures.json';
import infoDoc from '../../public/anatomy/structure-info.json';
import { conditionReference } from '../consult/ui/condition-reference.js';
import { anatomyStore, deriveVisual, initialState, reduce } from './anatomy-state.js';
import { AnatomyRegistry, type RegistryDoc } from './registry.js';
import { describeStructure, type InfoDoc } from './structure-info.js';

const registry = new AnatomyRegistry(registryDoc as unknown as RegistryDoc);
const info = infoDoc as unknown as InfoDoc;
const structures = registry.all().filter((s) => s.kind === 'structure');

describe('registry (generated by tools/anatomy-pipeline)', () => {
  it('has unique ids and unique GLB node names', () => {
    const ids = registry.all().map((s) => s.id);
    expect(new Set(ids).size).toBe(ids.length);
    const nodes = structures.map((s) => s.node);
    expect(new Set(nodes).size).toBe(nodes.length);
  });

  it('keeps GLB node names dot-free (three.js GLTFLoader strips dots) and never file-derived', () => {
    for (const s of structures) {
      expect(s.node).toBeTruthy();
      expect(s.node).not.toMatch(/[.[\]:/]/);
      expect(s.node).not.toMatch(/FJ\d+/); // BodyParts3D file ids must not leak into ids
      expect(s.id).not.toMatch(/FJ\d+/);
    }
  });

  it('resolves every structure from its node name, and every parent exists', () => {
    for (const s of structures) expect(registry.idForNode(s.node!)).toBe(s.id);
    for (const s of registry.all()) if (s.parent) expect(registry.has(s.parent)).toBe(true);
  });

  it('exposes the first vertical slice: lungs, airways, vessels, skeleton, body shell', () => {
    expect(registry.systemsWithGeometry().sort()).toEqual(['respiratory', 'skeletal', 'surface']);
    expect(registry.leaves('respiratory.lung.right')).toHaveLength(3);
    expect(registry.leaves('respiratory.lung.left')).toHaveLength(2);
    expect(registry.has('respiratory.airway.trachea')).toBe(true);
    expect(registry.leaves('skeletal.thoracic-cage').length).toBe(24 + 1 + 1); // ribs, sternum, cartilages
    expect(registry.leaves('skeletal.vertebral-column').length).toBe(7 + 12 + 5 + 1);
  });

  it('flags generated lobe envelopes as approximate and nothing else', () => {
    const approx = structures.filter((s) => s.approximate).map((s) => s.id);
    expect(approx).toHaveLength(5);
    expect(approx.every((id) => id.startsWith('respiratory.lung.'))).toBe(true);
  });

  it('stays inside the standalone-Quest triangle budget', () => {
    expect(registryDoc.totalTriangles).toBeLessThanOrEqual(150_000);
  });

  it('answers hierarchy and alias queries', () => {
    expect(registry.isWithin('respiratory.lung.right.upper-lobe', 'respiratory.lung.right')).toBe(true);
    expect(registry.isWithin('respiratory.lung.left.upper-lobe', 'respiratory.lung.right')).toBe(false);
    expect(registry.ancestors('respiratory.lung.right.upper-lobe').map((a) => a.id)).toEqual([
      'respiratory.lung.right',
      'respiratory',
    ]);
    expect(registry.findByAlias('Right Upper Lobe')).toBe('respiratory.lung.right.upper-lobe');
    expect(registry.findByAlias('windpipe')).toBe('respiratory.airway.trachea');
    expect(registry.findByAlias('nonsense')).toBeNull();
  });
});

describe('anatomy state reducer', () => {
  const start = initialState(registry);

  it('starts with respiratory in focus, skeleton as context, body hidden', () => {
    expect(start.systemModes).toEqual({ respiratory: 'active', skeletal: 'ghost', surface: 'hidden' });
    expect(start.selectedId).toBeNull();
  });

  it('SET_ANATOMICAL_SYSTEM focuses one system and ghosts the other', () => {
    const next = reduce(start, { type: 'SET_ANATOMICAL_SYSTEM', system: 'skeletal' }, registry);
    expect(next.systemModes).toMatchObject({ skeletal: 'active', respiratory: 'ghost', surface: 'hidden' });
  });

  it('ignores systems that are not loaded yet (muscular, nervous)', () => {
    expect(reduce(start, { type: 'SET_ANATOMICAL_SYSTEM', system: 'muscular' }, registry)).toBe(start);
    expect(reduce(start, { type: 'SET_ANATOMICAL_SYSTEM', system: 'nervous' }, registry)).toBe(start);
  });

  it('toggles the body shell without disturbing the other layers', () => {
    const on = reduce(start, { type: 'SET_ANATOMICAL_SYSTEM', system: 'surface' }, registry);
    expect(on.systemModes).toEqual({ respiratory: 'active', skeletal: 'ghost', surface: 'ghost' });
    expect(reduce(on, { type: 'SET_ANATOMICAL_SYSTEM', system: 'surface' }, registry).systemModes.surface).toBe('hidden');
  });

  it('selects, and deselects on a second selection of the same structure', () => {
    const id = 'respiratory.airway.trachea';
    const sel = reduce(start, { type: 'SELECT_STRUCTURE', structureId: id }, registry);
    expect(sel.selectedId).toBe(id);
    expect(reduce(sel, { type: 'SELECT_STRUCTURE', structureId: id }, registry).selectedId).toBeNull();
  });

  it('ignores unknown structure ids', () => {
    expect(reduce(start, { type: 'SELECT_STRUCTURE', structureId: 'nope' }, registry)).toBe(start);
    expect(reduce(start, { type: 'ISOLATE_STRUCTURE', structureId: 'nope' }, registry)).toBe(start);
  });

  it('isolates, clears isolation, and resets', () => {
    const id = 'respiratory.lung.left.upper-lobe';
    const iso = reduce(start, { type: 'ISOLATE_STRUCTURE', structureId: id }, registry);
    expect(iso).toMatchObject({ isolatedId: id, selectedId: id });
    expect(reduce(iso, { type: 'CLEAR_ISOLATION' }, registry).isolatedId).toBeNull();
    expect(reduce(iso, { type: 'RESET_VIEW' }, registry)).toEqual(start);
  });

  it('opens and closes information for the selection', () => {
    const id = 'respiratory.diaphragm';
    const open = reduce(start, { type: 'SHOW_CLINICAL_INFORMATION', structureId: id }, registry);
    expect(open).toMatchObject({ selectedId: id, infoOpen: true });
    expect(reduce(open, { type: 'HIDE_CLINICAL_INFORMATION' }, registry).infoOpen).toBe(false);
  });

  it('does not allocate new state for no-op hover', () => {
    const hov = reduce(start, { type: 'HOVER_STRUCTURE', structureId: 'respiratory.diaphragm' }, registry);
    expect(reduce(hov, { type: 'HOVER_STRUCTURE', structureId: 'respiratory.diaphragm' }, registry)).toBe(hov);
  });

  it('notifies store subscribers only on real change', () => {
    anatomyStore.init(registry);
    let calls = 0;
    const off = anatomyStore.subscribe(() => calls++);
    anatomyStore.dispatch({ type: 'SET_ANATOMICAL_SYSTEM', system: 'muscular' }); // ignored
    anatomyStore.dispatch({ type: 'SELECT_STRUCTURE', structureId: 'respiratory.diaphragm' });
    off();
    expect(calls).toBe(1);
  });
});

describe('X-ray findings', () => {
  it('every illustrative finding points at structures that exist in the anatomy registry', () => {
    for (const key of ['pneumonia', 'tuberculosis', 'copd', 'heart failure', 'lung cancer']) {
      const finding = conditionReference(key)!.xray!;
      expect(finding.structureIds.length).toBeGreaterThan(0);
      for (const id of finding.structureIds) expect(registry.has(id), `${key}: ${id}`).toBe(true);
    }
  });
});

describe('highlight', () => {
  const start = initialState(registry);
  const lobe = 'respiratory.lung.right.lower-lobe';

  it('glows a structure and everything inside it without selecting it or opening a card', () => {
    const lit = reduce(start, { type: 'HIGHLIGHT_STRUCTURES', structureIds: ['respiratory.lung.right'] }, registry);
    expect(lit.selectedId).toBeNull();
    expect(lit.infoOpen).toBe(false);
    expect(deriveVisual(lit, registry, lobe).emphasis).toBe(1);
    expect(deriveVisual(lit, registry, 'respiratory.lung.left.upper-lobe').emphasis).toBe(0);
  });

  it('keeps a highlighted lobe translucent so what is inside it stays visible', () => {
    const lit = reduce(start, { type: 'HIGHLIGHT_STRUCTURES', structureIds: [lobe] }, registry);
    const v = deriveVisual(lit, registry, lobe);
    expect(v.opacity).toBeGreaterThan(deriveVisual(start, registry, lobe).opacity);
    expect(v.opacity).toBeLessThan(1);
  });

  it('ignores unknown ids, is cleared by CLEAR_HIGHLIGHT and RESET_VIEW, and is a no-op when unchanged', () => {
    const lit = reduce(start, { type: 'HIGHLIGHT_STRUCTURES', structureIds: [lobe, 'nope'] }, registry);
    expect(lit.highlightIds).toEqual([lobe]);
    expect(reduce(lit, { type: 'HIGHLIGHT_STRUCTURES', structureIds: [lobe] }, registry)).toBe(lit);
    expect(reduce(lit, { type: 'CLEAR_HIGHLIGHT' }, registry).highlightIds).toEqual([]);
    expect(reduce(lit, { type: 'RESET_VIEW' }, registry).highlightIds).toEqual([]);
    expect(reduce(start, { type: 'CLEAR_HIGHLIGHT' }, registry)).toBe(start);
  });
});

describe('deriveVisual', () => {
  const start = initialState(registry);

  it('makes ghost layers visible but never pickable, so they cannot block a pinch', () => {
    const rib = deriveVisual(start, registry, 'skeletal.thoracic-cage.rib.right.3');
    expect(rib).toMatchObject({ visible: true, pickable: false });
    expect(rib.opacity).toBeLessThan(0.3);
  });

  it('hides the body shell by default and never makes it pickable', () => {
    expect(deriveVisual(start, registry, 'surface.torso').visible).toBe(false);
    const shown = reduce(start, { type: 'SET_ANATOMICAL_SYSTEM', system: 'surface' }, registry);
    expect(deriveVisual(shown, registry, 'surface.torso').pickable).toBe(false);
  });

  it('keeps lung envelopes translucent so airways stay visible, until selected', () => {
    const lobe = 'respiratory.lung.right.upper-lobe';
    expect(deriveVisual(start, registry, lobe).opacity).toBeLessThan(1);
    const sel = reduce(start, { type: 'SELECT_STRUCTURE', structureId: lobe }, registry);
    expect(deriveVisual(sel, registry, lobe)).toMatchObject({ opacity: 1, emphasis: 1, pickable: true });
  });

  it('isolating a group shows exactly its descendants', () => {
    const iso = reduce(start, { type: 'ISOLATE_STRUCTURE', structureId: 'respiratory.lung.right' }, registry);
    const visible = structures.filter((s) => deriveVisual(iso, registry, s.id).visible).map((s) => s.id).sort();
    expect(visible).toEqual(registry.leaves('respiratory.lung.right').sort());
  });
});

describe('approximate lobe envelopes', () => {
  const lobes = structures.filter((s) => s.id.startsWith('respiratory.lung.') && s.id.endsWith('-lobe'));

  it('are labelled as illustrative volumes in their display name', () => {
    expect(lobes).toHaveLength(5);
    for (const lobe of lobes) expect(lobe.name).toMatch(/illustrative volume/i);
  });

  it('are never eligible as clinical evidence, nor are groups that contain them', () => {
    for (const lobe of lobes) expect(registry.isEvidenceEligible(lobe.id)).toBe(false);
    expect(registry.isEvidenceEligible('respiratory.lung.right')).toBe(false);
    expect(registry.isEvidenceEligible('respiratory')).toBe(false);
  });

  it('leave the real BodyParts3D airways and vessels eligible', () => {
    for (const id of [
      'respiratory.airway.trachea',
      'respiratory.airway.main-bronchus.left',
      'respiratory.airway.bronchial-tree.right.upper-lobe',
      'respiratory.vessel.pulmonary-artery.right',
      'respiratory.vessel.pulmonary-vein.left',
      'respiratory.vessel',
      'skeletal',
    ]) {
      expect(registry.isEvidenceEligible(id)).toBe(true);
    }
  });

  it('carry an always-visible notice on the info card; real structures do not', () => {
    for (const lobe of lobes) {
      const card = describeStructure(registry, info, lobe.id)!;
      expect(card.notice).toMatch(/not an actual lung surface/i);
      expect(card.notice).toMatch(/not for clinical reasoning/i);
    }
    expect(describeStructure(registry, info, 'respiratory.airway.trachea')!.notice).toBeNull();
  });
});

describe('structure information content', () => {
  it('describes every structure without throwing, and says so when a shape is approximate', () => {
    for (const s of registry.all()) expect(describeStructure(registry, info, s.id)).not.toBeNull();
    const lobe = describeStructure(registry, info, 'respiratory.lung.right.upper-lobe')!;
    expect(lobe.approximate).toBe(true);
    expect(lobe.summary).toMatch(/approximate envelope/i);
  });

  it('is marked unreviewed', () => {
    expect(info.reviewStatus).toBe('unreviewed');
  });

  it('contains no diagnosis, medication or dosing language', () => {
    const everything = [...Object.values(info.entries), ...Object.values(info.prefixes)].join(' ');
    expect(everything).not.toMatch(/\b(mg|mcg|dose|dosage|prescri\w+|diagnos\w+|treat\w*|medicat\w+)\b/i);
  });
});
